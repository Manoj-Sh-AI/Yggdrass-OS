// Isolated synthetic study checks; never touches app authentication or Brain APIs.
const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const URL = 'http://127.0.0.1:3002/design-studies/open-air/';
const shots = path.resolve(__dirname, '../../api/runtime');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1344, height: 896 } });
    const page = await context.newPage(); const errors = []; const failures = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.status() >= 400) failures.push(r.url()); });
    await page.goto(URL, { waitUntil: 'networkidle' });
    await page.locator('.desk').waitFor();
    await page.waitForTimeout(700);
    fs.mkdirSync(shots, { recursive: true });
    await page.screenshot({ path: path.join(shots, 'open-air-desktop.png') });
    const captureBounds = await page.locator('#capture-open').boundingBox();
    assert.ok(captureBounds.y + captureBounds.height <= 896, 'Desktop capture must fit in the reference viewport');
    assert.equal(await page.locator('.agenda-row').count(), 3);
    const goal = await page.locator('.routine h4').textContent();
    await page.getByRole('button', { name: 'Start ritual' }).click();
    await page.getByRole('button', { name: 'Mark progress' }).click();
    assert.equal(await page.getByRole('progressbar').getAttribute('aria-valuenow'), '40');
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.getByRole('progressbar').getAttribute('aria-valuenow'), '40');
    await page.getByRole('button', { name: 'Complete ritual' }).click();
    assert.equal(await page.getByRole('progressbar').getAttribute('aria-valuenow'), '100');
    assert.equal(await page.locator('.routine h4').textContent(), goal);
    await page.locator('[data-task=chapter]').check();
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.locator('#focus-count').textContent(), '2 / 3');
    await page.locator('#capture-open').click();
    await page.locator('#capture-title').fill('A synthetic lakeside thought');
    await page.locator('#capture-body').fill('Leave a little room. <script>bad()</script>');
    await page.getByRole('button', { name: 'Keep this thought' }).click();
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('.wider-picture summary').click();
    assert.equal(await page.locator('.wider-picture').evaluate(e=>e.open),true);
    await page.locator('#notes-view').click();
    await page.keyboard.press('Escape');
    await page.locator('#search-open').click();
    await page.locator('#search-field').fill('lakeside');
    assert.equal(await page.locator('#search-results .note-row').count(), 1);
    await page.locator('#search-field').press('ArrowDown');
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#note-title').textContent(), 'A synthetic lakeside thought');
    assert.match(await page.locator('#note-body').textContent(), /<script>bad\(\)<\/script>/);
    await page.keyboard.press('Escape');
    await page.locator('#search-open').click();
    await page.locator('#search-field').fill('no-such-thought-zz');
    assert.match(await page.locator('#search-results').textContent(), /No thoughts match/);
    await page.keyboard.press('Escape');
    await page.locator('#appearance-open').click();
    await page.locator('#reduce-transparency').check();
    assert.equal(await page.locator('body').getAttribute('data-reduced'), 'true');
    await page.locator('#reduce-motion').check();
    await page.getByRole('button', { name: 'Night', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#scene-name').textContent === 'Night');
    await page.locator('#reduce-transparency').uncheck();
    await page.keyboard.press('Escape');
    await page.screenshot({ path: path.join(shots, 'open-air-night.png') });
    await page.locator('#moment-open').click();
    assert.equal(await page.locator('#moment-dialog').evaluate(d => d.open), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#moment-open').evaluate(e => e === document.activeElement), true);
    await page.locator('#appearance-open').click();
    await page.getByRole('button', { name: 'Afternoon', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#scene-name').textContent === 'Afternoon');
    await page.keyboard.press('Escape');
    await page.locator('#appearance-open').click();
    await page.getByRole('button', { name: 'Morning', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#scene-name').textContent === 'Morning');
    await page.keyboard.press('Escape');
    await page.screenshot({ path: path.join(shots, 'open-air-morning.png') });
    await page.locator('#appearance-open').click();
    await page.getByRole('button', { name: 'Afternoon', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#scene-name').textContent === 'Afternoon');
    await page.keyboard.press('Escape');
    for (const [width,height,name] of [[820,1180,'tablet'],[390,844,'mobile'],[320,760,'narrow']]) {
      await page.setViewportSize({width,height});
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, name + ' overflow');
      await page.screenshot({ path: path.join(shots, 'open-air-' + name + '.png'), fullPage: true });
    }
    await page.locator('#appearance-mobile').click();
    await page.locator('#reduce-transparency').check();
    assert.equal(await page.locator('body').getAttribute('data-reduced'),'true');
    await page.keyboard.press('Escape');
    // Failed storage must retain the full capture draft rather than feign a save.
    await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('test storage failure'); }; });
    await page.locator('#capture-top').click();
    await page.locator('#capture-title').fill('Keep my unsaved draft');
    await page.getByRole('button', { name: 'Keep this thought' }).click();
    assert.match(await page.locator('#capture-error').textContent(), /Could not save/);
    assert.equal(await page.locator('#capture-title').inputValue(), 'Keep my unsaved draft');
    await page.keyboard.press('Escape');
    // A separate fresh context checks missing-scene fallback and system preferences.
    const fallback = await browser.newContext({viewport:{width:1344,height:896}, reducedMotion:'reduce'});
    const offline = await fallback.newPage();
    await offline.route('**/autumn-sunrise-clear-*.webp', r => r.abort());
    await offline.goto(URL,{waitUntil:'networkidle'});
    await offline.locator('#appearance-open').click();
    await offline.getByRole('button',{name:'Morning',exact:true}).click();
    await offline.locator('#appearance-error').filter({hasText:'could not load'}).waitFor();
    assert.equal(await offline.locator('#scene-name').textContent(),'Afternoon');
    assert.equal(await offline.locator('.desk').evaluate(e=>getComputedStyle(e).animationName),'none');
    assert.deepEqual(errors,[]); assert.deepEqual(failures,[]);
    console.log('PASS: desktop/tablet/390/320 layouts; capture → search → note → reload; literal-text safety; task and routine persistence; fixed routine goal; search empty state; scenery and missing-asset fallback; reduced transparency/motion; modal Escape/focus restoration; storage-failure draft preservation.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode=1; });
