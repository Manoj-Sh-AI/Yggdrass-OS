"""Build the maps and lint.md for a library; optionally log their size.

Usage:
    python -m yggdras.data.maps.build BRAIN_REPO [--out DIR] [--log]

Writes atlas.md, shelf-map.md, relationship-map.md and lint.md to
library/00-manual/generated/ (or DIR). Never touches a note. --log appends one dated line
to generated/map-size-log.md, the one generated file that is not deterministic; Lia never
loads it.
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

from yggdras import config
from yggdras.data.graph import structural as st
from yggdras.data.maps import checks
from yggdras.data.maps.atlas import atlas
from yggdras.data.maps.notes import TAXONOMY, load_notes, map_version
from yggdras.data.maps.relations import relationship_map
from yggdras.data.maps.shelf import shelf_map

MAP_FILES = ("atlas.md", "shelf-map.md", "relationship-map.md")
LINT_FILE = "lint.md"
SIZE_LOG = "map-size-log.md"
# Map text is denser than prose (slugs, pipes): calibrated against Anthropic's count_tokens
# on the real brain, 2026-11-01 (9,857 tokens for 23,189 characters).
CHARS_PER_TOKEN = 2.35
WARN_TOKENS, SPLIT_TOKENS = 20_000, 25_000


def estimate_tokens(text: str) -> int:
    return round(len(text) / CHARS_PER_TOKEN)


def build_maps(root: Path, graph: dict | None = None) -> dict[str, str]:
    """The three maps for the library at *root* (its `library/` folder)."""
    shelves = st.mapped_shelves()
    graph = graph or st.build_map(root, shelves)
    notes = load_notes(root, shelves)
    version = map_version(root, shelves)
    taxonomy = root / TAXONOMY
    return {
        "atlas.md": atlas(
            notes, taxonomy.read_text(encoding="utf-8") if taxonomy.is_file() else "", version
        ),
        "shelf-map.md": shelf_map(notes, version),
        "relationship-map.md": relationship_map(graph, notes, version),
    }


def problems(root: Path, maps: dict[str, str], hard: bool) -> list[checks.Problem]:
    notes = load_notes(root, st.mapped_shelves())
    found = [p for n in notes.values() for p in checks.description_problems(n, hard)]
    return found + checks.facts_in_maps(maps, notes, hard)


def lint(root: Path, maps: dict[str, str], found: list[checks.Problem], hard: bool) -> str:
    notes = load_notes(root, st.mapped_shelves())
    tokens = {name: estimate_tokens(text) for name, text in maps.items()}
    total = sum(tokens.values())
    out = [
        "# Lint",
        "",
        "Generated by code. Never loaded into Lia's prompt.",
        "",
        "## Map size",
        "",
    ]
    out += [f"- {name}: about {n} tokens" for name, n in tokens.items()]
    out.append(f"- total: about {total} tokens")
    if total > SPLIT_TOKENS:
        out.append(f"- **SPLIT:** over {SPLIT_TOKENS}; split the maps per area (maps-design §7)")
    elif total > WARN_TOKENS:
        out.append(f"- **WARNING:** over {WARN_TOKENS}; plan the per-area split")
    out += ["", f"## Description and map rules (hard rules {'ON' if hard else 'OFF'})", ""]
    rows = sorted(found, key=lambda p: (p.severity != "hard", p.slug, p.message))
    out += [f"- {p.severity}: `{p.slug}`: {p.message}" for p in rows] or ["- none"]
    out += ["", "## Sensitive descriptions (for Manoj to read after any change)", ""]
    sensitive = sorted((n for n in notes.values() if n.sensitive), key=lambda n: n.slug)
    out += [f"- `{n.slug}`: {n.description}" for n in sensitive]
    if not sensitive:
        out.append("- none")
    return "\n".join(out) + "\n"


def size_line(maps: dict[str, str], notes: int, day: dt.date) -> str:
    tokens = {name: estimate_tokens(text) for name, text in maps.items()}
    parts = " · ".join(f"{name} {n}" for name, n in tokens.items())
    return f"- {day.isoformat()}: {notes} notes · {parts} · total {sum(tokens.values())}"


def write(out_dir: Path, files: dict[str, str]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")


def run(
    repo: Path,
    out_dir: Path | None = None,
    graph: dict | None = None,
    log_day: dt.date | None = None,
) -> list[checks.Problem]:
    """Build and write the maps and lint.md; return the problems found."""
    root = repo / st.LIBRARY
    out_dir = out_dir or st.generated_dir(repo)
    hard = config.hard_description_rules()
    maps = build_maps(root, graph)
    found = problems(root, maps, hard)
    write(out_dir, {**maps, LINT_FILE: lint(root, maps, found, hard)})
    if log_day:
        log = out_dir / SIZE_LOG
        notes = len(load_notes(root, st.mapped_shelves()))
        head = (
            ""
            if log.is_file()
            else "# Map size log\n\nOne line a month. Never loaded into Lia's prompt.\n\n"
        )
        with log.open("a", encoding="utf-8", newline="\n") as f:
            f.write(head + size_line(maps, notes, log_day) + "\n")
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="maps", description=__doc__.splitlines()[0])
    parser.add_argument("brain", type=Path, help="the brain repo")
    parser.add_argument("--out", type=Path, help="write here instead of generated/")
    parser.add_argument("--log", action="store_true", help="append today's map size to the log")
    args = parser.parse_args(argv)
    if not (args.brain / st.LIBRARY).is_dir():
        print(f"not a brain repo with library/: {args.brain}", file=sys.stderr)
        return 2
    found = run(args.brain, args.out, log_day=dt.date.today() if args.log else None)
    hard = [p for p in found if p.severity == "hard"]
    print(f"maps written; {len(hard)} hard problem(s), {len(found) - len(hard)} warning(s)")
    return 1 if hard else 0


if __name__ == "__main__":
    sys.exit(main())
