-- The brain in PostgreSQL: catalogue, text, links and history, in schema `brain`.
-- Derived from the markdown (D1): droppable and rebuildable by the loader.
-- The catalogue (notes) and the text (note_bodies) are separate tables, so a shelf read
-- never drags note bodies with it.

CREATE TABLE brain.areas (
    area_code   text PRIMARY KEY CHECK (area_code ~ '^[0-9]{2}$'),  -- '04': the key, never the name
    name        text NOT NULL,
    node_range  text,                       -- display only
    hub_slug    text,                       -- FK added below (areas and notes refer to each other)
    belongs_here text,
    not_here    text,
    sort_order  integer NOT NULL
);

CREATE TABLE brain.notes (
    slug         text PRIMARY KEY,
    title        text NOT NULL,
    type         text NOT NULL,
    area_code    text NOT NULL REFERENCES brain.areas (area_code) ON DELETE RESTRICT,
    also_area    text REFERENCES brain.areas (area_code) ON DELETE RESTRICT,
    shelf_no     integer,                   -- display and sort only: never a key, never cited
    description  text,
    status       text,
    sensitivity  text,
    review_date  date,
    decided_date date,
    updated_at   timestamptz,
    archived_at  timestamptz,
    version      integer NOT NULL DEFAULT 1  -- bumped on every write (triggers below)
);

ALTER TABLE brain.areas
    ADD CONSTRAINT areas_hub_slug_fkey
    FOREIGN KEY (hub_slug) REFERENCES brain.notes (slug) ON DELETE SET NULL;

CREATE TABLE brain.verbs (
    verb    text PRIMARY KEY,
    inverse text NOT NULL,
    meaning text
);

-- One row per link, in the direction it is written (D31); the reverse is a query.
CREATE TABLE brain.relationships (
    from_slug text NOT NULL REFERENCES brain.notes (slug) ON DELETE CASCADE,
    verb      text NOT NULL REFERENCES brain.verbs (verb) ON DELETE RESTRICT,
    to_slug   text NOT NULL REFERENCES brain.notes (slug) ON DELETE CASCADE,
    kind      text NOT NULL,
    PRIMARY KEY (from_slug, verb, to_slug),
    CHECK (from_slug <> to_slug)
);
CREATE INDEX relationships_from_slug_idx ON brain.relationships (from_slug);
CREATE INDEX relationships_to_slug_idx ON brain.relationships (to_slug);

CREATE TABLE brain.note_bodies (
    slug text PRIMARY KEY REFERENCES brain.notes (slug) ON DELETE CASCADE,
    body text NOT NULL
);

CREATE TABLE brain.aliases (
    alias text PRIMARY KEY,
    slug  text NOT NULL REFERENCES brain.notes (slug) ON DELETE CASCADE
);

CREATE TABLE brain.dated_items (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug  text NOT NULL REFERENCES brain.notes (slug) ON DELETE CASCADE,
    date  date NOT NULL,
    kind  text NOT NULL CHECK (kind IN ('event', 'review', 'start', 'end', 'decided')),
    label text
);
CREATE INDEX dated_items_date_idx ON brain.dated_items (date);

-- History: the one table that never cascades. A deleted note leaves its rows here, with
-- slug set to null and slug_text keeping the name.
CREATE TABLE brain.changes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       text REFERENCES brain.notes (slug) ON DELETE SET NULL,
    slug_text  text NOT NULL,
    kind       text NOT NULL CHECK (kind IN ('add', 'replace', 'remove', 'archive', 'restore')),
    old_text   text,
    new_text   text,
    actor      text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX changes_slug_idx ON brain.changes (slug);
CREATE INDEX changes_created_at_idx ON brain.changes (created_at);

-- What Lia reads: the three maps, rendered from the rows. Never live queries.
CREATE TABLE brain.map_cache (
    map_name      text PRIMARY KEY CHECK (map_name IN ('atlas', 'shelf', 'relationships')),
    rendered_text text NOT NULL,
    map_version   text NOT NULL,            -- a hash of rendered_text
    built_at      timestamptz NOT NULL
);

-- version: every update of a note, or of its body, bumps it by one.
CREATE FUNCTION brain.bump_note_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.version := OLD.version + 1;
    RETURN NEW;
END $$;

CREATE TRIGGER notes_bump_version BEFORE UPDATE ON brain.notes
    FOR EACH ROW EXECUTE FUNCTION brain.bump_note_version();

CREATE FUNCTION brain.bump_note_version_from_body() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE brain.notes SET version = version WHERE slug = NEW.slug;
    RETURN NEW;
END $$;

CREATE TRIGGER note_bodies_bump_version AFTER UPDATE ON brain.note_bodies
    FOR EACH ROW EXECUTE FUNCTION brain.bump_note_version_from_body();
